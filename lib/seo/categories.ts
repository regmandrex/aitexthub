/**
 * Single source of truth for tool categories.
 *
 * `key` is the value stored on each tool's `category` field in seo/registry.ts.
 * `slug` is the URL segment under /ai-tools/ and is deliberately decoupled from
 * the key so we can use plural, keyword-friendly URLs without rewriting the
 * registry (e.g. key 'developer-tool' -> slug 'developer-tools').
 */
export type ToolCategory = {
  key: string;
  slug: string;
  /** Short label used in listings and breadcrumbs. */
  title: string;
  /** H1 on the category page. */
  heading: string;
  /** One-line summary used on the hub and in card listings. */
  description: string;
  /** <title> for the category page. */
  seoTitle: string;
  /** Meta description for the category page. */
  metaDescription: string;
  /**
   * Plural noun phrase for "View all N ...". Set where the title does not read
   * naturally in that slot (e.g. title "AI Humanizers" -> "AI humanizer tools").
   * Defaults to the lowercased title.
   */
  ctaNoun?: string;
};


/** Category display order on the hub page and in listings. */
export const CATEGORY_ORDER: string[] = TOOL_CATEGORIES.map((c) => c.key);

const BY_KEY = new Map(TOOL_CATEGORIES.map((c) => [c.key, c]));
const BY_SLUG = new Map(TOOL_CATEGORIES.map((c) => [c.slug, c]));

export function getCategoryByKey(key: string): ToolCategory | undefined {
  return BY_KEY.get(key);
}

export function getCategoryBySlug(slug: string): ToolCategory | undefined {
  return BY_SLUG.get(slug);
}

/** URL path for a category page, given the registry category key. */
export function categoryHref(key: string): string | undefined {
  const category = BY_KEY.get(key);
  return category ? `/ai-tools/${category.slug}` : undefined;
}

/** Number of registered tools in a category, keyed by category key. */
export const CATEGORY_COUNTS: Record<string, number> = toolPages.reduce<Record<string, number>>(
  (acc, page) => {
    if (!page.category || page.noindex) return acc;
    acc[page.category] = (acc[page.category] ?? 0) + 1;
    return acc;
  },
  {}
);

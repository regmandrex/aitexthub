"use client";

import { useCallback, useState } from 'react';
import ToolTextArea from './ToolTextArea';

type ImageWatermarkDetectorToolProps = {
  modelName?: string;
};

const DEC = new TextDecoder('latin1');

function bytesToAscii(bytes: Uint8Array, start: number, len: number) {
  return DEC.decode(bytes.subarray(start, start + len));
}

/** Scan raw file bytes for known metadata / provenance / watermark markers. */
function analyze(bytes: Uint8Array) {
  const findings: string[] = [];
  const head = bytesToAscii(bytes, 0, Math.min(bytes.length, 4));
  let format = 'unknown';
  if (head.startsWith('\x89PNG')) format = 'PNG';
  else if (bytes[0] === 0xff && bytes[1] === 0xd8) format = 'JPEG';
  else if (head === 'RIFF') format = 'WEBP';
  else if (head === 'GIF8') format = 'GIF';

  // Search the whole file (as latin1 text) for marker strings.
  const text = DEC.decode(bytes);

  const markers: Array<[RegExp, string]> = [
    [/c2pa|contentauth|content credentials|urn:uuid:.*c2pa/i, 'C2PA / Content Credentials (provenance manifest)'],
    [/jumbf|jumd/i, 'JUMBF box (container used by C2PA)'],
    [/<x:xmpmeta|xmlns:xmp|http:\/\/ns\.adobe\.com\/xap/i, 'XMP metadata block'],
    [/Exif\x00\x00/, 'EXIF metadata'],
    [/photoshop|8BIM/i, 'Photoshop / IPTC metadata'],
    [/Software\x00|generated by|openai|dall-?e|midjourney|stable ?diffusion|firefly|imagen|gemini/i, 'AI-generation software / model tag'],
    [/ICC_PROFILE/i, 'ICC color profile'],
  ];

  for (const [re, label] of markers) {
    if (re.test(text)) findings.push(label);
  }
  return { format, findings };
}

export function ImageWatermarkDetectorTool({ modelName }: ImageWatermarkDetectorToolProps) {
  const label = modelName ?? 'AI';
  const [report, setReport] = useState('');
  const [busy, setBusy] = useState(false);

  const handleFile = useCallback(
    async (file: File | null) => {
      if (!file) {
        setReport('');
        return;
      }
      if (!file.type.startsWith('image/')) {
        setReport('Please choose an image file (PNG, JPEG, WebP, etc.).');
        return;
      }
      setBusy(true);
      try {
        const buf = new Uint8Array(await file.arrayBuffer());
        const { format, findings } = analyze(buf);
        const lines = [
          `${label} image metadata scan`,
          '',
          `File: ${file.name}`,
          `Format: ${format}`,
          `Size: ${(file.size / 1024).toFixed(1)} KB`,
          '',
          findings.length
            ? `Embedded metadata / watermark markers found (${findings.length}):`
            : 'No embedded metadata or provenance markers were found in this file.',
          ...findings.map((f) => `  • ${f}`),
          '',
          findings.length
            ? 'These are metadata-level markers. You can strip them with the matching Watermark Remover tool (canvas re-encode).'
            : 'Note: this scan reads metadata only. A clean scan does NOT rule out a steganographic watermark such as Google SynthID, which is woven into the pixels and cannot be detected by any in-browser tool.',
        ];
        setReport(lines.join('\n'));
      } catch {
        setReport('That image could not be read.');
      } finally {
        setBusy(false);
      }
    },
    [label],
  );

  return (
    <div className="space-y-4">
      <div className="grid gap-4 md:grid-cols-[1fr,1fr]">
        <div className="space-y-3 rounded-xl border border-slate-200 bg-slate-50 p-4">
          <label className="block text-sm font-semibold text-slate-800">Upload image</label>
          <input
            type="file"
            accept="image/*"
            onChange={(e) => handleFile(e.target.files?.[0] ?? null)}
            className="block w-full text-sm text-slate-700 file:mr-4 file:rounded-lg file:border-0 file:bg-brand-700 file:px-4 file:py-2 file:text-sm file:font-semibold file:text-white hover:file:bg-brand-800"
          />
          <p className="text-sm text-slate-600">
            Reads the file&rsquo;s embedded metadata in your browser — EXIF, XMP,
            ICC, and C2PA content credentials / provenance manifests — and
            reports any {label} watermark markers it finds. Nothing is uploaded.
          </p>
          {busy ? <p className="text-xs text-slate-500">Scanning…</p> : null}
        </div>
        <ToolTextArea
          label="Scan report"
          value={report}
          onChange={setReport}
          placeholder="Your metadata scan report will appear here."
          rows={14}
          readOnly
        />
      </div>
      <p className="text-xs text-slate-500">
        Detects metadata-level watermarks (C2PA/EXIF/XMP). It cannot detect
        steganographic pixel watermarks such as Google SynthID — no public
        in-browser tool can.
      </p>
    </div>
  );
}

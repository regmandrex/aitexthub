"use client";

import { GenericTextProcessorTool } from './GenericTextProcessorTool';

export function ChatGPTDetectorTool() {
  const processText = (text: string): string => {
    if (!text.trim()) {
      return '';
    }
    
    const words = text.trim().split(/\s+/).length;
    const sentences = text.split(/[.!?]+/).filter(s => s.trim().length > 0).length;
    const avgWordsPerSentence = sentences > 0 ? (words / sentences).toFixed(1) : '0';
    const paragraphs = text.split(/\n\s*\n/).filter(p => p.trim().length > 0).length;
    
    return `Text Analysis:\n\n• Length: ${text.length} characters\n• Words: ${words}\n• Sentences: ${sentences}\n• Paragraphs: ${paragraphs}\n• Average words per sentence: ${avgWordsPerSentence}\n\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n\nNote: This tool is currently in development. AI detection results will appear here once API integration is complete.`;
  };

  return (
    <GenericTextProcessorTool
      processText={processText}
      inputLabel="Text to Analyze"
      outputLabel="Detection Results"
      inputPlaceholder="Paste your text here to check if it was generated by ChatGPT..."
      outputPlaceholder="AI detection results will appear here..."
    />
  );
}
